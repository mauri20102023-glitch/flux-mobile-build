import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const web = join(root, "web", "flux-ath");
const mime = {
  "master-shell.css": "text/css; charset=utf-8",
  "master-shell.js": "text/javascript; charset=utf-8",
  "index.html": "text/html; charset=utf-8",
  "app.js": "text/javascript; charset=utf-8",
  "command-center.js": "text/javascript; charset=utf-8",
  "study-board.js": "text/javascript; charset=utf-8",
  "study-model.js": "text/javascript; charset=utf-8",
  "command-center.css": "text/css; charset=utf-8",
  "styles.css": "text/css; charset=utf-8",
  "sw.js": "text/javascript; charset=utf-8",
  "icon.svg": "image/svg+xml",
  "manifest.webmanifest": "application/manifest+json",
};
const assets = {};
for (const [filename, mimeType] of Object.entries(mime)) {
  assets[`/${filename}`] = { mimeType, base64: (await readFile(join(web, filename))).toString("base64") };
}
await writeFile(join(root, "src", "embedded-assets.ts"),
  `// Generated by npm run embed:web. Public web files only.\nexport const EMBEDDED_ASSETS: Record<string, { mimeType: string; base64: string }> = ${JSON.stringify(assets)};\n`);
